// Exports the housing database to JSON for use without a database connection.
//   data/export/properties.json  one record per property: details, floor plans with price history, resolved 61 factors,
//                                precomputed location factors. Use "key" (normalized address) as the stable identifier.
//   data/export/evidence.json    every kept evidence row with source URL and quote (for "why" explanations)
//   data/export/factors.json     the 61-factor catalog
// Usage (from web/): node --env-file=.env.local scripts/export-json.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { connect } from "./lib/db.ts";

type Row = Record<string, any>;
const db = await connect();
const t0 = performance.now();
const [props, plans, prices, status, evidence, catalog] = await Promise.all([
  db.query<Row>(`select id, normalized_address as key, name, street, zip, latitude, longitude, property_type, official_website,
                        management_company, phone from properties order by name`),
  db.query<Row>(`select id, property_id, name, bedrooms, bathrooms, square_feet, floor_plan_url from floor_plans order by bedrooms nulls last, name`),
  db.query<Row>(`select l.floor_plan_id, l.property_id, l.rent_min, l.rent_max, l.pricing_basis, l.pricing_frequency, l.price_type,
                        l.available_date, l.observed_at, s.url as source_url
                 from listings l join scraped_sources s on s.id = l.source_id order by l.observed_at desc`),
  db.query<Row>(`select property_id, factor_key, state, building_claim, max_numeric, best_text from property_factor_status`),
  db.query<Row>(`select a.property_id, p.normalized_address as property_key, a.attribute_key, a.factor_key, a.scope, a.value_state,
                        a.value_text, a.value_numeric, a.unit_of_measure, a.raw_text, a.source_url, a.source_title,
                        a.extraction_method, a.confidence, a.verification_status, a.extracted_at
                 from extracted_attributes a join properties p on p.id = a.property_id
                 where a.verification_status <> 'rejected' order by p.normalized_address, a.attribute_key`),
  db.query<Row>(`select number, key, label, category, value_kind, acquisition, confirm_scopes, notes from factor_catalog order by number`),
]);

const num = (v: unknown) => (v == null ? null : Number(v));
const byProp = <T extends Row>(rows: T[]) => rows.reduce((m, r) => (m.get(r.property_id)?.push(r) ?? m.set(r.property_id, [r]), m), new Map<string, T[]>());
const plansBy = byProp(plans), pricesBy = byProp(prices), statusBy = byProp(status);
const pricesByPlan = prices.reduce((m, r) => (r.floor_plan_id && (m.get(r.floor_plan_id)?.push(r) ?? m.set(r.floor_plan_id, [r])), m), new Map<string, Row[]>());
const price = (r: Row) => ({ rent_min: num(r.rent_min), rent_max: num(r.rent_max), basis: r.pricing_basis, frequency: r.pricing_frequency,
  type: r.price_type, available_date: r.available_date, observed_at: r.observed_at, source_url: r.source_url });

const properties = props.map((p) => {
  const factors: Record<string, Row> = {};
  for (const s of statusBy.get(p.id) ?? [])
    if (s.state !== "unknown" || s.building_claim)
      factors[s.factor_key] = { state: s.state, ...(s.building_claim && { building_claim: true }),
        ...(s.max_numeric != null && { value: num(s.max_numeric) }), ...(s.best_text && { text: s.best_text }) };
  return {
    id: p.id, key: p.key, name: p.name, street: p.street, zip: p.zip, latitude: num(p.latitude), longitude: num(p.longitude),
    property_type: p.property_type, official_website: p.official_website, management_company: p.management_company, phone: p.phone,
    floor_plans: (plansBy.get(p.id) ?? []).map((f) => ({ name: f.name, bedrooms: num(f.bedrooms), bathrooms: num(f.bathrooms),
      square_feet: num(f.square_feet), floor_plan_url: f.floor_plan_url, prices: (pricesByPlan.get(f.id) ?? []).map(price) })),
    unlinked_prices: (pricesBy.get(p.id) ?? []).filter((r) => !r.floor_plan_id).map(price),
    factors,   // only factors with evidence; anything absent is UNKNOWN
  };
});

const dir = join(import.meta.dirname, "../../data/export");
mkdirSync(dir, { recursive: true });
const meta = { generated_at: new Date().toISOString(), note: "Generated by web/scripts/export-json.ts. Absent factor = UNKNOWN. Location factors are straight-line walking estimates." };
writeFileSync(join(dir, "properties.json"), JSON.stringify({ ...meta, count: properties.length, properties }));
writeFileSync(join(dir, "evidence.json"), JSON.stringify({ ...meta, count: evidence.length, evidence: evidence.map(({ property_id, ...e }) => ({ ...e, value_numeric: num(e.value_numeric), confidence: num(e.confidence) })) }));
writeFileSync(join(dir, "factors.json"), JSON.stringify({ ...meta, factors: catalog }, null, 1));
console.log(`exported ${properties.length} properties, ${evidence.length} evidence rows in ${Math.round(performance.now() - t0)} ms`);
await db.close();
